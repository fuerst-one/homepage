export function atlasText(locale: Locale, text: string): string {
  if (locale !== "de") return text;
  if (ATLAS_DE[text]) return ATLAS_DE[text];
  const translated = ATLAS_DE[text.trim()];
  return translated ? text.replace(text.trim(), translated) : text;
}

export function atlasTerm(locale: Locale, value: string): string {
  if (locale !== "de" || ATLAS_DE[value]) return atlasText(locale, value);
  const reason = /^(Missing comparable values:|Missing or invalid:) (.+)$/.exec(
    value,
  );
  if (reason)
    return `${atlasText(locale, reason[1])} ${reason[2]
      .split(", ")
      .map((part) => atlasText(locale, part))
      .join(", ")}`;
  return value
    .split(" / ")
    .map((part) => atlasText(locale, part))
    .join(" / ");
}

export function atlasCount(locale: Locale, count: number) {
  return `${count.toLocaleString(locale)} ${atlasText(locale, count === 1 ? "project" : "projects")}`;
}

